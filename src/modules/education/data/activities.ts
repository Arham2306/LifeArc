export function getActivitiesForStage(
  stage: ActiveSchoolStage | 'university'
): ExtracurricularTemplate[] {
  const effectiveStage: ActiveSchoolStage =
    stage === 'university' ? 'high_school' : stage;
  return EXTRACURRICULAR_CATALOG.filter((item) => item.stage === effectiveStage);
}

export function getActivityTemplateById(id: string): ExtracurricularTemplate | undefined {
  return EXTRACURRICULAR_CATALOG.find((item) => item.id === id);
}

export function getActivityRoleDisplay(activity: ActiveExtracurricular): {
  label: string;
  isLeader: boolean;
} {
  if (activity.role === 'member') {
    return { label: 'Member', isLeader: false };
  }
  return {
    label: `${activity.leaderTitle} 🏅`,
    isLeader: true,
  };
}

