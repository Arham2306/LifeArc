export type CrimeId =
  | 'shoplifting'
  | 'vandalism'
  | 'pickpocketing'
  | 'fraud_scam'
  | 'burglary'
  | 'vehicle_theft'
  | 'robbery'
  | 'bank_heist';

export type CrimeTier = 'petty' | 'mid' | 'high_stakes';

/** Statutory seriousness of the offense, separate from juvenile/adult forum. */
export type OffenseClass = 'misdemeanor' | 'felony';

/** Legal forum determined by character age at the time of the attempt (< 18 juvenile, >= 18 adult). */
export type LegalJurisdiction = 'juvenile' | 'adult';

export type CrimeOutcomeStatus =
  | 'undetected'
  | 'aborted'
  | 'warned'
  | 'dismissed'
  | 'acquitted'
  | 'fined'
  | 'probation'
  | 'imprisoned';

export type PrisonSecurityLevel = 'minimum' | 'medium' | 'maximum';

/** Independent legal progression status of an incident or criminal record. */
export type CrimeLegalStatus =
  | 'attempted'
  | 'detected'
  | 'arrested'
  | 'pending_trial'
  | 'acquitted'
  | 'convicted'
  | 'sentence_completed'
  | 'sealed'
  | 'expunged';

/** Independent public/third-party awareness dimension (orthogonal to legal status and police detection). */
export type CrimeExposureLevel = 'private' | 'witness_known' | 'publicly_reported';

/** Per-record sentence lifecycle status so historical convictions stay isolated from concurrent cases. */
export type CrimeRecordSentenceStatus = 'not_applicable' | 'active' | 'completed';

export type ProbationConditionId =
  | 'supervision_checkins'
  | 'community_service'
  | 'restitution_payments'
  | 'activity_restriction'
  | 'no_new_offenses';

