export interface CrimeRecordEntry {
  id: string;
  crimeId: CrimeId;
  title: string;
  tier: CrimeTier;
  offenseClass: OffenseClass;
  jurisdiction: LegalJurisdiction;
  age: number;
  year: number;
  executionSucceeded: boolean;
  detected: boolean;
  injured: boolean;
  outcome: CrimeOutcomeStatus;
  /** Public/third-party awareness level for this incident (separate from legal status). */
  exposure?: CrimeExposureLevel;
  /** Per-record sentence lifecycle status linked to originating prison/probation term. */
  sentenceStatus?: CrimeRecordSentenceStatus;
  /** Gross attempted proceeds generated by execution before arrest forfeiture or retained profit. */
  attemptedPayout: number;
  /** Net criminal proceeds retained by the player (0 when caught or unsuccessful). */
  payout: number;
  /** Illicit proceeds confiscated by the state upon conviction (never reduces victim restitution). */
  stateForfeitedProceeds?: number;
  /** Assets/value explicitly confirmed returned to the victim. */
  recoveredPropertyReturnedToVictim?: number;
  /** Uncompensated victim loss remaining after confirmed victim returns. */
  remainingVictimLoss?: number;
  /** Court-ordered victim restitution imposed separately from statutory fines. */
  restitutionImposed?: number;
  /** Portion of victim restitution paid at settlement. */
  restitutionPaid?: number;
  fineImposed: number;
  finePaid: number;
  attorneyFeePaid: number;
  sentenceYears: number;
  /** True when a juvenile adjudication has been automatically sealed at/after age 18. */
  sealed: boolean;
  /** True when an eligible adult conviction has been formally expunged or pardoned. */
  expunged: boolean;
  /** True when an adult violent felony conviction was cleared via Governor's Executive Pardon. */
  pardoned?: boolean;
  /** Age at which the last court rehabilitation or pardon petition for this record was denied. */
  lastPetitionDeniedAge?: number | null;
}

export interface PendingCourtCase {
  id: string;
  crimeId: CrimeId;
  title: string;
  tier: CrimeTier;
  offenseClass: OffenseClass;
  jurisdiction: LegalJurisdiction;
  arrestedAtAge: number;
  arrestedAtYear: number;
  executionSucceeded: boolean;
  injured: boolean;
  attemptedPayout: number;
  baseFine: number;
  baseSentenceYears: number;
  /** Active pre-trial legal stage (distinct from conviction). */
  legalStatus?: 'arrested' | 'pending_trial';
  /** Independent public/institutional awareness level at apprehension. */
  exposure?: CrimeExposureLevel;
  /** True when this offense occurred while the character already had active probation supervision. */
  offendedOnProbation?: boolean;
  /** Happiness delta already applied at arrest so verdict settlement avoids double-stacking. */
  arrestHappinessApplied?: number;
  /**
   * Non-injury physical arrest stress already applied at apprehension (distinct from
   * `roll.injured` physical getaway trauma) so verdict settlement avoids double-stacking stress.
   */
  arrestHealthApplied?: number;
  /** Explicit evidence flags when supplied by a caller/event. */
  explicitWitnessSignal?: boolean;
  institutionalReportFiled?: boolean;
}

