export type CrimeId =
  | 'shoplifting'
  | 'vandalism'
  | 'pickpocketing'
  | 'fraud_scam'
  | 'burglary'
  | 'vehicle_theft'
  | 'robbery'
  | 'bank_heist';

export type CrimeTier = 'petty' | 'mid' | 'high_stakes';

/** Statutory seriousness of the offense, separate from juvenile/adult forum. */
export type OffenseClass = 'misdemeanor' | 'felony';

/** Legal forum determined by character age at the time of the attempt (< 18 juvenile, >= 18 adult). */
export type LegalJurisdiction = 'juvenile' | 'adult';

export type CrimeOutcomeStatus =
  | 'undetected'
  | 'aborted'
  | 'warned'
  | 'dismissed'
  | 'acquitted'
  | 'fined'
  | 'probation'
  | 'imprisoned';

export type PrisonSecurityLevel = 'minimum' | 'medium' | 'maximum';

export interface CrimeRecordEntry {
  id: string;
  crimeId: CrimeId;
  title: string;
  tier: CrimeTier;
  offenseClass: OffenseClass;
  jurisdiction: LegalJurisdiction;
  age: number;
  year: number;
  executionSucceeded: boolean;
  detected: boolean;
  injured: boolean;
  outcome: CrimeOutcomeStatus;
  /** Gross attempted proceeds generated by execution before arrest forfeiture or retained profit. */
  attemptedPayout: number;
  /** Net criminal proceeds retained by the player (0 when caught or unsuccessful). */
  payout: number;
  fineImposed: number;
  finePaid: number;
  attorneyFeePaid: number;
  sentenceYears: number;
  /** True when a juvenile adjudication has been automatically sealed at/after age 18. */
  sealed: boolean;
  /** True when an eligible adult conviction has been formally expunged. */
  expunged: boolean;
}

export interface PendingCourtCase {
  id: string;
  crimeId: CrimeId;
  title: string;
  tier: CrimeTier;
  offenseClass: OffenseClass;
  jurisdiction: LegalJurisdiction;
  arrestedAtAge: number;
  arrestedAtYear: number;
  executionSucceeded: boolean;
  injured: boolean;
  attemptedPayout: number;
  baseFine: number;
  baseSentenceYears: number;
}

export interface PrisonState {
  facilityName: string;
  securityLevel: PrisonSecurityLevel;
  chargeTitle: string;
  yearsTotal: number;
  yearsServed: number;
  yearsRemaining: number;
  behaviorScore: number;
  paroleEligibleAtServed: number;
  actionsTakenThisYear: number;
  lastActionAge: number | null;
  lastProgressedAge: number | null;
}

export interface ProbationState {
  chargeTitle: string;
  jurisdiction: LegalJurisdiction;
  yearsRemaining: number;
  startedAtAge: number;
  lastProgressedAge: number | null;
}

export interface PlayerCrimeState {
  policeHeat: number;
  notoriety: number;
  unpaidFines: number;
  attemptsThisYear: number;
  attemptCountLifetime: number;
  lastAttemptAge: number | null;
  lastProgressedAge: number | null;
  pendingCase: PendingCourtCase | null;
  prison: PrisonState | null;
  probation: ProbationState | null;
  records: CrimeRecordEntry[];
}

export interface CrimeTemplate {
  id: CrimeId;
  title: string;
  description: string;
  icon: string;
  tier: CrimeTier;
  /** Minimum character age required to attempt this crime. */
  minAge: number;
  /** Statutory offense class; juvenile vs. adult jurisdiction is derived separately from age. */
  adultOffenseClass: OffenseClass;
  payoutMin: number;
  payoutMax: number;
  baseExecutionProbability: number;
  baseDetectionProbability: number;
  canCauseInjury: boolean;
  baseInjuryProbability: number;
  injuryHealthLossMin: number;
  injuryHealthLossMax: number;
  karmaPenalty: number;
  heatGain: number;
  notorietyGain: number;
  baseFineMin: number;
  baseFineMax: number;
  baseSentenceYearsMin: number;
  baseSentenceYearsMax: number;
}

export interface CrimeRollEvaluation {
  crimeId: CrimeId;
  jurisdiction: LegalJurisdiction;
  executionProbability: number;
  detectionProbability: number;
  injuryProbability: number;
  executionSucceeded: boolean;
  detected: boolean;
  injured: boolean;
  attemptedPayout: number;
  injuryHealthLoss: number;
}

export interface CrimeEligibilityResult {
  eligible: boolean;
  reason?: string;
}
