export const CRIME_CATALOG_MAP: Record<CrimeId, CrimeTemplate> = CRIME_CATALOG.reduce(
  (acc, item) => {
    acc[item.id] = item;
    return acc;
  },
  {} as Record<CrimeId, CrimeTemplate>,
);

export function isValidCrimeId(value: unknown): value is CrimeId {
  return typeof value === 'string' && Object.prototype.hasOwnProperty.call(CRIME_CATALOG_MAP, value);
}

export function getCrimeTemplate(crimeId: CrimeId): CrimeTemplate {
  return CRIME_CATALOG_MAP[crimeId];
}

